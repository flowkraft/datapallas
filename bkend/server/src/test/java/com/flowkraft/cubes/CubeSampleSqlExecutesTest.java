	/** The sentence a refusal says, or a failure naming the SQL it produced instead. */
	private String refusalOf(SqlThatShouldNotBeWritten attempt) {
		try {
			fail("This was refused by nothing and came back as:\n" + attempt.write());
			return "";
		} catch (IllegalArgumentException refused) {
			return refused.getMessage();
		} catch (Exception other) {
			throw new IllegalStateException(other);
		}
	}

	private interface SqlThatShouldNotBeWritten {
		String write() throws Exception;
	}

	/** Every row of an answer, as its columns came back. */
	private List<List<Object>> table(Connection connection, String sql) throws Exception {
		List<List<Object>> rows = new ArrayList<>();
		try (Statement statement = connection.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
			int columns = rs.getMetaData().getColumnCount();
			while (rs.next()) {
				List<Object> row = new ArrayList<>();
				for (int i = 1; i <= columns; i++) row.add(rs.getObject(i));
				rows.add(row);
			}
		}
		return rows;
	}

	/** A number as the driver handed it over, whatever box it came in. */
	private static double number(Object value) {
		if (value == null) return 0;
		return value instanceof Number ? ((Number) value).doubleValue()
				: Double.parseDouble(value.toString());
	}

	private String ask(CubeOptions cube, String vendor, Object... keysAndValues) {
		Map<String, Object> request = new LinkedHashMap<>();
		for (int i = 0; i < keysAndValues.length; i += 2) {
			request.put(keysAndValues[i].toString(), keysAndValues[i + 1]);
		}
		return CubeVariableBinding.bound(CubeSqlGenerator.buildQuery(cube, request, vendor), AS_ADMIN)
				.toInlineSql(vendor);
	}

	/**
	 * Whoever this test asks as. Story 31 ships an {@code access_filter} on Support Desk, so from
	 * now on a Support Desk statement carries it and the answer depends on who is asking. These
	 * tests are about the numbers the desk holds, so they ask as an admin, whom the filter's third
	 * line lets see the whole desk. A cube without an access filter names no variable, and binding
	 * hands its query back untouched.
	 */
	private static final Map<String, String> AS_ADMIN = Map.of(
			"dp_user_id", "The Sample Sweep",
			"dp_user_email", "sweep@support.cube-demo.example",
			"dp_user_groups", "",
			"dp_user_role", "admin");

	private Map<String, Object> filterOn(String member, String operator, Object... values) {
		Map<String, Object> filter = new LinkedHashMap<>();
		filter.put("member", member);
		filter.put("operator", operator);
		filter.put("values", java.util.Arrays.asList(values));
		return filter;
	}

	private Number oneNumber(Connection connection, String sql) throws Exception {
		try (Statement statement = connection.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
			if (!rs.next()) {
				throw new IllegalStateException("No row came back from:\n" + sql);
			}
			return (Number) rs.getObject(1);
		}
	}

	private long rowsOf(Connection connection, String sql) throws Exception {
		try (Statement statement = connection.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
			long rows = 0;
			while (rs.next()) rows++;
			return rows;
		}
	}

	private List<String> textColumn(Connection connection, String sql) throws Exception {
		List<String> values = new ArrayList<>();
		try (Statement statement = connection.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
			while (rs.next()) {
				if (rs.getObject(1) != null) values.add(rs.getString(1));
			}
		}
		return values;
	}

	private List<Double> numberColumn(Connection connection, String sql, int column) throws Exception {
		List<Double> values = new ArrayList<>();
		try (Statement statement = connection.createStatement(); ResultSet rs = statement.executeQuery(sql)) {
			while (rs.next()) values.add(rs.getDouble(column));
		}
		return values;
	}
